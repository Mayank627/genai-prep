#Conditional statements and loops in Python

age = 25

if age < 18:
    print("Minor")

elif age > 18:
    print("Adult")

else:
    print("Exactly 18")

#Loops

#For Loop

skills = ["python", "java", "C++"]
for skill in skills:
    print(skill)

for i in range(1, 5):
    print(i)

#While Loop
count = 0
while count < 5:
    print(count)
    count += 1
    

